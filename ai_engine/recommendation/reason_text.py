
"""Reason text generator for study plans.

Generates beginner-friendly explanations using actual recommendation
reasons, learner mastery data, and daily study time.
"""

from typing import Any

from ai_engine.recommendation.adapter import normalize_analysis


def make_reason(
    analysis: dict[str, Any],
    plan: dict[str, Any],
) -> str:
    """Generate a deterministic explanation of the study plan."""

    normalized = normalize_analysis(analysis)

    recommended = plan.get("recommended_topics", [])
    daily_minutes = plan.get(
        "daily_minutes",
        normalized.daily_minutes,
    )

    if not recommended:
        return (
            f"Your daily study budget is {daily_minutes} minutes, "
            "which is below the minimum 10 minutes needed for a study topic. "
            "Please increase your available study time to receive recommendations."
        )

    first_item = recommended[0]

    first_topic = first_item.get("topic", "your selected topic")
    first_activity = first_item.get("activity", "study")
    first_minutes = first_item.get("minutes", 0)

    # Use the actual reason generated by the recommendation engine.
    first_reason = first_item.get("reason", "").strip()

    if not first_reason:
        score = normalized.topic_scores.get(first_topic)

        if score is None:
            first_reason = (
                f"{first_topic} has not been assessed yet, "
                "so it needs an initial assessment."
            )
        else:
            first_reason = (
                f"{first_topic} has a mastery score of "
                f"{round(score)}%, so it has been selected for "
                f"{first_activity}."
            )

    # Explain the study-time allocation.
    time_reason = (
        f"Your plan allocates {first_minutes} minutes to "
        f"{first_topic}, within your daily budget of "
        f"{daily_minutes} minutes."
    )

    # Include a second recommendation when available.
    if len(recommended) > 1:
        second_item = recommended[1]
        second_reason = second_item.get("reason", "").strip()

        if second_reason:
            return (
                f"{first_reason} "
                f"{second_reason} "
                f"{time_reason}"
            )

    return f"{first_reason} {time_reason}"
